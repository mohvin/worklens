// Bundle the replay runs in ../../samples/runs into the web app:
//   public/samples/<name>/frames/*.jpg, run.bpmn   (static files)
//   src/generated/samples.ts                        (run.json content, imported by the loader)
// Runs before `next dev` and `next build`, so the deployed demo needs no backend.
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, "../../../samples/runs");
const pub = path.resolve(here, "../public/samples");
const gen = path.resolve(here, "../src/generated");

const names = existsSync(src) ? readdirSync(src).filter((n) => existsSync(path.join(src, n, "run.json"))) : [];
rmSync(pub, { recursive: true, force: true });
mkdirSync(gen, { recursive: true });
const entries = [];
for (const name of names) {
  const d = path.join(src, name);
  mkdirSync(path.join(pub, name), { recursive: true });
  cpSync(path.join(d, "frames"), path.join(pub, name, "frames"), { recursive: true });
  if (existsSync(path.join(d, "run.bpmn"))) cpSync(path.join(d, "run.bpmn"), path.join(pub, name, "run.bpmn"));
  const run = JSON.parse(readFileSync(path.join(d, "run.json"), "utf8"));
  run.id = name;
  const frames = readdirSync(path.join(d, "frames")).filter((f) => f.endsWith(".jpg")).map((f) => parseInt(f.slice(1, 6), 10) - 1);
  entries.push({ name, run, frames, mtime: statSync(path.join(d, "run.json")).mtimeMs });
}
const out = `// Generated by scripts/sync-samples.mjs. Do not edit.
import type { Run } from "@/lib/types";
export interface Sample { run: Run; frames: number[]; mtime: number }
export const SAMPLES: Record<string, Sample> = ${JSON.stringify(Object.fromEntries(entries.map((e) => [e.name, { run: e.run, frames: e.frames, mtime: e.mtime }])), null, 1)};
`;
writeFileSync(path.join(gen, "samples.ts"), out);
console.log(`samples: ${names.length ? names.join(", ") : "none found in " + src}`);
